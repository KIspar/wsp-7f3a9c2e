export const sellingLayouts=definitions.map(([name,rules],i)=>({id:`selling-layout-${String(i+1).padStart(2,'0')}`,version:1,name,rules,ratios:['1:1','3:4','4:3','9:16','16:9'],textDensity:'简洁',fields:['商品名称','已确认卖点'],category:'通用'}));
export function resolveSellingLayout(ref:{id:string;version:number}) {
 const layout=sellingLayouts.find(l=>l.id===ref.id&&l.version===ref.version);
 if(!layout)throw Error('卖点版式不可用，请重新选择');
 return layout;
}
